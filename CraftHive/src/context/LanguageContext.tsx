// ─── CONTEXT ─────────────────────────────────────────────────────────
interface LangCtx {
  language: Language
  setLanguage: (l: Language) => void
  t: (key: string, params?: Record<string, string>) => string
  speechLang: string
}

const LangContext = createContext<LangCtx>({
  language: 'en',
  setLanguage: () => { },
  t: (k) => k,
  speechLang: 'en-GH',
})

export function LangProvider({ children }: { children: React.ReactNode }) {
  const [language, setLangState] = useState<Language>('en')

  useEffect(() => {
    AsyncStorage.getItem('crafthive_language').then(v => {
      if (v && TRANSLATIONS[v as Language]) setLangState(v as Language)
    })
  }, [])

  const setLanguage = (l: Language) => {
    setLangState(l)
    AsyncStorage.setItem('crafthive_language', l)
  }

  // t() looks up the key in the selected language,
  // falls back to English, then returns the key itself as last resort.
  const t = (key: string, params?: Record<string, string>): string => {
    const dict = TRANSLATIONS[language]
    let text = (dict && dict[key]) || EN[key] || key
    if (params) {
      Object.entries(params).forEach(([k, v]) => {
        text = text.replace(`{${k}}`, v)
      })
    }
    return text
  }

  return (
    <LangContext.Provider value={{ language, setLanguage, t, speechLang: SPEECH_LANG[language] }}>
      {children}
    </LangContext.Provider>
  )
}

export const useLang = () => useContext(LangContext)